// 후기의 재구매 횟수를 시안 문구로 옮긴다.
//
// 상품 리뷰 목록·사진 뷰어·리뷰 상세가 같은 칩 줄을 쓴다. 뷰끼리는 서로 가져다 쓸 수 없어 여기에 둔다.
// 값은 실제 구매 이력이 아니라 백엔드가 평점에 따라 뽑아 저장한 표시용 값이다(sever#217).

/** 시안의 "재구매 2회". 0회면 칩을 두지 않는다 — 0회가 절반을 넘어 대부분의 카드에 붙는다 */
export function toRepurchaseLabels(count: number): string[] {
  return count > 0 ? [`재구매 ${count}회`] : [];
}
