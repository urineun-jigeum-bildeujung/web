// 전화번호 하이픈 자동 처리(QA No.165, #526)와 휴대폰 번호 검사(QA No.151, #594) 테스트.
import { expect, test } from "vitest";

import { formatPhoneInput, isMobilePhoneNumber } from "./phone-number";

// 치는 도중의 모양까지 본다. 한 자씩 칠 때마다 이 함수를 거친다
test.each([
  ["", ""],
  ["010", "010"],
  ["0101", "010-1"],
  ["0101234", "010-1234"],
  ["01012345", "010-1234-5"],
  ["01012345678", "010-1234-5678"],
  // 서울은 지역번호가 두 자리다
  ["02", "02"],
  ["0212", "02-12"],
  ["021234567", "02-123-4567"],
  ["0212345678", "02-1234-5678"],
  // 010이 아닌 번호는 열 자리까지 3-3-4, 열한 자리면 3-4-4다
  ["031123", "031-123"],
  ["0311234567", "031-123-4567"],
  ["03112345678", "031-1234-5678"],
  // 050 평생·안심번호는 앞자리가 네 자리다. 열한 자리까지 4-3-4, 열두 자리면 4-4-4다 (#526 리뷰)
  ["0504", "0504"],
  ["0504123", "0504-123"],
  ["05051234567", "0505-123-4567"],
  ["050412345678", "0504-1234-5678"],
])("%s → %s", (typed, shown) => {
  expect(formatPhoneInput(typed)).toBe(shown);
});

test("숫자가 아닌 글자는 버린다", () => {
  expect(formatPhoneInput("010abc1234-가5678")).toBe("010-1234-5678");
});

test("이미 하이픈이 든 값도 같은 모양으로 둔다", () => {
  expect(formatPhoneInput("010-1234-5678")).toBe("010-1234-5678");
});

test("열한 자리를 넘는 숫자는 버린다", () => {
  expect(formatPhoneInput("010123456789")).toBe("010-1234-5678");
  expect(formatPhoneInput("02123456789")).toBe("02-1234-5678");
});

// 050 번호만 한 자리 더 받는다. 열한 자리로 자르면 `0504-1234-5678`의 마지막 8이 사라졌다
test("050 번호는 열두 자리까지 받고 그 뒤는 버린다", () => {
  expect(formatPhoneInput("0504-1234-5678")).toBe("0504-1234-5678");
  expect(formatPhoneInput("0504123456789")).toBe("0504-1234-5678");
});

// 휴대폰 인증은 이 검사를 통과할 때만 인증 버튼을 보인다 (QA No.151)
test.each(["01012345678", "010-1234-5678", "0111234567", "011-123-4567", "01912345678"])(
  "%s는 휴대폰 번호다",
  (text) => {
    expect(isMobilePhoneNumber(text)).toBe(true);
  },
);

test.each([
  ["", "비었다"],
  ["010123456", "아홉 자리다"],
  ["010123456789", "열두 자리다"],
  ["01212345678", "012는 이동통신 번호가 아니다"],
  ["0212345678", "서울 지역번호다"],
  ["010-1234-567a", "숫자가 아닌 글자가 섞였다"],
])("%s는 휴대폰 번호가 아니다 (%s)", (text) => {
  expect(isMobilePhoneNumber(text)).toBe(false);
});
