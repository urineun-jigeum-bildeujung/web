export type GuideSection = {
  /** 안내 안의 소제목. 시안에서 13px·짙은 색으로 구분되는 줄이다 */
  heading: string;
  /** 소제목 아래 본문. 시안의 줄바꿈 하나가 한 줄이다 */
  lines: string[];
  /**
   * 시안에서 이 소제목 앞에 빈 줄이 있으면 참. 본문 한 줄 높이(18px)만큼 띄운다.
   *
   * **빈 줄이 있는 자리와 없는 자리가 안내마다 다르다.** 규칙을 찾아 통일하려다
   * 시안과 달라지므로, 판단하지 않고 시안에 있는 그대로 옮긴다.
   */
  spacedBefore?: boolean;
};

